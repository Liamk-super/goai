export function normalizeLocale(value?: string | null): Locale {
  return value?.toLowerCase().startsWith("zh") ? "zh-CN" : "en";
}

export function translate(locale: Locale, key: string, values: Record<string, string | number> = {}): string {
  const template = locale === "zh-CN" ? (zhCN[key] ?? key) : (enUS[key] ?? key);
  const rendered = template.replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? `{${name}}`));
  return locale === "zh-CN"
    ? rendered.replaceAll("\u52bf\u80fd\u5f15\u64ce", "爆款预测器").replaceAll("\u8bc4\u5ba1", "预测")
    : rendered;
}

export function hasTranslation(locale: Locale, key: string): boolean {
  const containsChinese = /[\u3400-\u9fff]/u.test(key);
  if (locale === "zh-CN") return containsChinese || Object.hasOwn(zhCN, key);
  return !containsChinese || Object.hasOwn(enUS, key);
}

